int main() {
    string s = "hola";
    int arr[3] = {1, 2, 3};
    cout << "size: " << s.size() << endl;
    cout << "arr: " << arr.size() << endl;
    cout << "to_string: " << to_string(5) + "!" << endl;
    cout << "stoi: " << stoi("12") + 1 << endl;
    cout << "max: " << max(2, 7) << endl;
    cout << "abs: " << abs(-3) << endl;
    return 0;
}
